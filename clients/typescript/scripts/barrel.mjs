// The root barrel of @voplica/connect: writes src/index.ts, re-exporting every module buf generates in src/
// (`*_pb.ts`) with `.js` specifiers, which Node ESM (NodeNext) requires.
//
// Protobuf packages may reuse a message name (`MPAFilter` is declared by voplica.api.ai.dataset and by
// voplica.api.character), and two `export *` lines exporting one name do not compile (TS2308). A module that exports
// such a shared name is re-exported name by name instead: the shared names under its package's last segment in
// PascalCase (`DatasetMPAFilter`, `DatasetMPAFilterSchema`), its other names unchanged; types with `export type`,
// values with `export`. Importing the module by its own path (`@voplica/connect/voplica/api/ai/dataset/dataset_pb`)
// keeps every plain name. The barrel fails rather than guess when two modules sharing a name derive the same prefix,
// or when an alias would equal another export of the root.
import { readdirSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const EXPORT_DECL = /^export\s+(type|interface|const|class|abstract class|function|enum)\s+([A-Za-z_$][\w$]*)/gm;
const PACKAGE_HEADER = /^\/\/ @generated from file \S+ \(package ([\w.]+),/m;

function pascalCase(segment) {
	return segment
		.split(/[-_]/)
		.filter(Boolean)
		.map((part) => part[0].toUpperCase() + part.slice(1))
		.join('');
}

/** The generated modules under `srcDir`, as posix paths relative to it, sorted. */
function generatedModules(srcDir, dir = '') {
	const found = [];
	for (const entry of readdirSync(join(srcDir, dir), { withFileTypes: true })) {
		const path = dir ? `${dir}/${entry.name}` : entry.name;
		if (entry.isDirectory()) found.push(...generatedModules(srcDir, path));
		else if (entry.name.endsWith('_pb.ts')) found.push(path);
	}
	return found.sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
}

/** The text of src/index.ts for the generated modules under `srcDir`. */
export function generateBarrel(srcDir) {
	const modules = generatedModules(srcDir).map((path) => {
		const text = readFileSync(join(srcDir, path), 'utf8');
		return {
			path,
			specifier: `./${path.replace(/\.ts$/, '.js')}`,
			protoPackage: text.match(PACKAGE_HEADER)?.[1],
			names: [...text.matchAll(EXPORT_DECL)].map((m) => ({ name: m[2], isType: m[1] === 'type' || m[1] === 'interface' })),
		};
	});
	const owners = new Map();
	for (const module of modules) {
		for (const { name } of module.names) owners.set(name, [...(owners.get(name) ?? []), module]);
	}
	const shared = new Set([...owners].filter(([, list]) => list.length > 1).map(([name]) => name));
	const prefixOf = (module) => {
		if (!module.protoPackage) throw new Error(`barrel: ${module.path} has no "@generated from file ... (package ...)" header`);
		return pascalCase(module.protoPackage.split('.').pop());
	};

	const lines = ['// Generated by scripts/barrel.mjs from the modules buf generates in src/; never edited by hand.'];
	const exported = new Map(); // a name the root exports -> the module it comes from
	const claim = (name, module) => {
		if (exported.has(name)) throw new Error(`barrel: the root would export "${name}" from both ${exported.get(name)} and ${module.path}`);
		exported.set(name, module.path);
	};
	for (const module of modules) {
		if (!module.names.some(({ name }) => shared.has(name))) {
			lines.push(`export * from "${module.specifier}";`);
			for (const { name } of module.names) claim(name, module);
			continue;
		}
		const prefix = prefixOf(module);
		for (const { name } of module.names.filter(({ name }) => shared.has(name))) {
			for (const other of owners.get(name)) {
				if (other !== module && prefixOf(other) === prefix) {
					throw new Error(
						`barrel: "${name}" is exported by ${module.path} (package ${module.protoPackage}) and ${other.path} ` +
							`(package ${other.protoPackage}), which derive the same alias prefix "${prefix}"`,
					);
				}
			}
		}
		const types = [];
		const values = [];
		for (const { name, isType } of module.names) {
			const as = shared.has(name) ? `${prefix}${name}` : name;
			claim(as, module);
			(isType ? types : values).push(as === name ? name : `${name} as ${as}`);
		}
		if (types.length) lines.push(`export type { ${types.join(', ')} } from "${module.specifier}";`);
		if (values.length) lines.push(`export { ${values.join(', ')} } from "${module.specifier}";`);
	}
	return `${lines.join('\n')}\n`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(realpathSync(process.argv[1])).href) {
	const src = fileURLToPath(new URL('../src/', import.meta.url));
	const text = generateBarrel(src);
	writeFileSync(join(src, 'index.ts'), text);
	const aliased = [...text.matchAll(/ as /g)].length;
	console.log(`barrel: src/index.ts re-exports ${text.split('\n').filter((l) => l.startsWith('export')).length} lines, ${aliased} aliased names`);
}
